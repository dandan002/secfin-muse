"""Generate the labelled desk-shorthand chat corpus for parser evals.

    uv run mock-ib-corpus --out out/chat_corpus.jsonl --n 300 --seed 20261027

Each line is one conversation: persona messages with gold labels, plus (for RFQs) our quote and
the persona's reaction. Generated by the same code the live personas use, so evals measure the
parser against exactly what the demo will throw at it.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from mockcore import rng

from . import personas as P

MIX = (  # persona, action, weight
    ("pb-alpha", "locate_blast", 30),
    ("pb-bravo", "locate_blast", 15),
    ("harbor-lending", "ioi", 15),
    ("kestrel-hf", "rfq", 15),
    ("delta-one", "internal_borrow", 10),
    ("juniper-hf", "rfq", 7),
    ("juniper-hf", "injection", 3),
    ("pb-alpha", "chatter", 5),
)


def conversation(r, i: int, at: datetime) -> dict[str, Any]:
    persona, action, _ = r.choices(MIX, [w for *_, w in MIX])[0]
    p = P.PERSONAS[persona]
    msgs: list[dict[str, Any]] = []

    def add(sender: str, d: P.Draft | str) -> None:
        if isinstance(d, str):
            msgs.append({"from": sender, "text": d})
        else:
            msgs.append({"from": sender, "text": d.text, "chips": d.chips, "label": d.label})

    if action == "locate_blast":
        for d in P.locate_blast(r, p, r.choice((1, 2, 3, 5, 8)), per_message=r.choice((None, 1, 3))):
            add(p.handle, d)
    elif action == "ioi":
        add(p.handle, P.ioi(r, p, r.choice((2, 3, 4, 6)), at=at))
    elif action == "internal_borrow":
        add(p.handle, P._locate_message(r, p, P.pick_instruments(r, 1)))
    elif action == "injection":
        add(p.handle, P.injection(r, p))
    elif action == "chatter":
        add(p.handle, P.chatter(r, p))
    else:
        d, hidden = P.rfq(r, p, at=at)
        add(p.handle, d)
        fee = round(hidden["maxFeeBps"] * r.uniform(0.85, 1.25))
        quote = r.choice((f"can show {fee}bps", f"{fee} open", f"we can do {fee}bp, {P.fmt_qty(r, hidden['qty'])}",
                          f"indic {fee / 100:.2f}%"))
        add("loandesk-agent", quote)
        out = P.react(r, p, quote, hidden)
        if out:
            add(p.handle, out[1])
    return {"conversationId": f"conv-{i:04d}", "persona": persona, "counterparty": p.cp_code,
            "room": p.room_id, "ts": at.isoformat(), "messages": msgs}


def generate(n: int, seed: int) -> list[dict[str, Any]]:
    rng.set_seed(seed)
    r = rng.fresh("ib", "corpus", n)
    start = datetime(2026, 10, 26, 13, 0, tzinfo=UTC)
    return [conversation(r, i, start + timedelta(minutes=2 * i)) for i in range(n)]


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="mock-ib-corpus")
    ap.add_argument("--out", type=Path, default=Path("out/chat_corpus.jsonl"))
    ap.add_argument("--n", type=int, default=300)
    ap.add_argument("--seed", type=int, default=20261027)
    args = ap.parse_args(argv)
    convs = generate(args.n, args.seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w") as f:
        for c in convs:
            f.write(json.dumps(c) + "\n")
    intents = Counter(m["label"]["intent"] for c in convs for m in c["messages"] if "label" in m)
    lines = sum(len(m["label"]["lines"]) for c in convs for m in c["messages"] if "label" in m)
    print(f"wrote {len(convs)} conversations, {lines} labelled lines {dict(intents)} to {args.out}")


if __name__ == "__main__":
    main()
